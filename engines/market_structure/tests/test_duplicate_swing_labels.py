# Two labels this many bars apart or fewer overlap when drawn.
NEAR = 30


def _replay(ohlc):
    """Return every permanent swing label the engine emits, as (side, text, price, bar)."""
    engine = StructureEngine(major_length=15)
    labels = []
    for i, (o, h, l, c) in enumerate(ohlc):
        ext = engine.update(Bar(index=i, open=o, high=h, low=l, close=c)).external
        if ext.broken_high_label is not None:
            labels.append(
                ("high", ext.broken_high_label, ext.broken_high_price, ext.broken_high_index)
            )
        if ext.broken_low_label is not None:
            labels.append(("low", ext.broken_low_label, ext.broken_low_price, ext.broken_low_index))
    return labels


def _stacked(labels, side):
    """Pairs of labels on the same price, close enough together to collide on the chart."""
    hits = []
    same_side = [x for x in labels if x[0] == side]
    for i, (_, t1, p1, b1) in enumerate(same_side):
        for _, t2, p2, b2 in same_side[i + 1 :]:
            if p1 == p2 and b1 != b2 and abs(b1 - b2) <= NEAR:
                hits.append((t1, b1, t2, b2, p1))
    return hits


def test_the_tie_actually_occurs():
    """Guard the fixtures: if the tied bars vanish, the regression tests below go vacuous."""
    assert LOW_TIE_BARS[89][2] == LOW_TIE_BARS[90][2] == 1828.44
    assert HIGH_TIE_BARS[50][1] == HIGH_TIE_BARS[51][1] == 2397.31


def test_no_stacked_low_labels():
    """A swing low that two bars tie for must be labelled once, not as LL and then HL."""
    hits = _stacked(_replay(LOW_TIE_BARS), "low")
    assert hits == [], f"stacked low labels: {hits}"


def test_no_stacked_high_labels():
    """The bearish mirror: the tied high must not be labelled HH twice."""
    hits = _stacked(_replay(HIGH_TIE_BARS), "high")
    assert hits == [], f"stacked high labels: {hits}"


def test_tied_swing_keeps_its_original_anchor():
    """The fix itself: the surviving label sits on the FIRST bar to make the extreme."""
    lows = [x for x in _replay(LOW_TIE_BARS) if x[0] == "low" and x[2] == 1828.44]
    assert len(lows) == 1, f"expected one label at 1828.44, got {lows}"
    assert lows[0][3] == 89, f"expected anchor on bar 89, got bar {lows[0][3]}"
