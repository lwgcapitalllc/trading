"""
Regression tests for the duplicate swing-label defect (fixed 2026-08-20).

THE DEFECT. When two bars print an IDENTICAL high (or low), the post-break rescan in
_process_external picks the LATER of them, because it scans newest-to-oldest with a strict
`<`. The label for that swing, however, was already anchored on the EARLIER bar. The
"have I already labelled this swing?" guard then compares price AND bar index, sees a
different bar index, concludes this is a brand new swing, and emits a second label at the
same price. In Pine those labels are never deleted, so they stack on the chart.

Measured before the fix, on the real XAUUSD cache: 7 stacked pairs in 186,759 M15 bars and
28 in 400,000 M1 bars. The low side reads `LL` beside `HL` (a visible contradiction, which
is how it was spotted); the high side reads `HH` beside `HH`, which just looks like a
slightly bold label and had gone unnoticed for the engine's whole life.

WATCHED RED. Both tests below fail against the pre-fix engine with exactly:

    test_no_stacked_low_labels  -> LL @1828.44 bar 89, then HL @1828.44 bar 90
    test_no_stacked_high_labels -> HH @2397.31 bar 50, then HH @2397.31 bar 51

They are NOT vacuous: `test_the_tie_actually_occurs` asserts the tied bars are present in
each fixture, so a fixture silently losing its tie turns that test red rather than letting
the two regression tests pass for the wrong reason.

The bars are REAL, taken from backtest/cache/XAUUSD__M15.csv, and inlined rather than read
from the cache so the tests carry no data dependency. Each window is the SHORTEST cold-start
replay that still reproduces (measured: 130 bars and 200 bars; 120 and 180 do not).
"""

